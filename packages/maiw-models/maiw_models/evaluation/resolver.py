"""
Phase 18D: Canonical entity resolver for evaluation graders.

Resolves surface-form text references to canonical entity IDs from the supplied
OperationalContextSnapshot (or context_entities list).

Design constraints (§9–§11):
  - Deterministic: same inputs → same output, always.
  - Bounded: only resolves to entities present in the supplied context.
  - No external lookups: no network, no disk, no LLM, no live graph.
  - No fuzzy global entity search: only exact canonical ID, known display name,
    and derivable normalized aliases (hyphen↔space↔underscore substitution only).
  - Canonical identity ≠ surface-form identity:
      "WAVE-17", "Wave 17", "wave-17" → canonical entity "wave-17"
      "Wave 18" must NOT resolve to "wave-17"

Alias derivation (§10 approved hierarchy):
  1. exact canonical ID                 — "wave-17"
  2. known canonical display name       — "Wave 17" (stored in entity metadata)
  3. approved normalized aliases        — derivable from canonical ID only:
       • hyphen → space  : "wave 17"
       • underscore → space: "wave 17"
       • hyphen → underscore: "wave_17"
       • all lowercased
  NO edit-distance, NO phonetic matching, NO substring containment.

Usage::

    resolver = EntityResolver.from_context_ids(context_entities)
    canonical = resolver.resolve("Wave 17")  # → "wave-17"
    canonical = resolver.resolve("wave seventeen")  # → None  (not an alias)
    canonical = resolver.resolve("Wave 18")  # → None  (wrong entity)
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field

# ── Alias generation ──────────────────────────────────────────────────────────


def _canonical_aliases(canonical_id: str) -> frozenset[str]:
    """
    Return the full set of approved surface-form aliases for a canonical entity ID.

    Only deterministic substitutions are applied — no fuzzy matching.

    >>> sorted(_canonical_aliases("wave-17"))
    ['wave 17', 'wave-17', 'wave_17']
    >>> sorted(_canonical_aliases("worker-A001"))
    ['worker a001', 'worker-a001', 'worker_a001']
    """
    normalized = canonical_id.lower()
    return frozenset(
        {
            normalized,  # exact: "wave-17"
            normalized.replace("-", " "),  # display: "wave 17"
            normalized.replace("_", " "),  # display (underscore): "wave 17"
            normalized.replace("-", "_"),  # alt underscore: "wave_17"
            normalized.replace("_", "-"),  # alt hyphen: "wave-17" (idempotent)
        }
    )


# ── Entity resolver ───────────────────────────────────────────────────────────


@dataclass
class ContextEntity:
    """
    Lightweight entity descriptor for evaluation context.

    canonical_id: the authoritative entity ID (e.g. "wave-17").
    display_names: human-readable names from entity metadata (optional).
                   These MUST come from the OperationalContextSnapshot or
                   fixture metadata — never generated by the resolver.
    """

    canonical_id: str
    display_names: list[str] = field(default_factory=list)

    @property
    def all_aliases(self) -> frozenset[str]:
        """All approved surface forms for this entity (lowercase)."""
        aliases = set(_canonical_aliases(self.canonical_id))
        for name in self.display_names:
            aliases.add(name.lower())
        return frozenset(aliases)


@dataclass
class ResolvedEntity:
    """Diagnostic record for a resolved entity reference (§13)."""

    model_reference: str  # text as it appeared in model response
    resolved_entity_id: str  # canonical ID it resolved to
    expected_entity_id: str  # expected canonical ID (from EvaluationCase)
    match: bool  # resolved_entity_id == expected_entity_id


class EntityResolver:
    """
    Deterministic canonical entity resolver bounded to a supplied context.

    Not a fuzzy matcher.  Resolves ONLY via:
      1. Exact canonical ID match (case-insensitive)
      2. Approved normalized aliases (hyphen↔space↔underscore)
      3. Supplied display names from entity metadata

    Returns None for any reference that does not resolve to a known context entity.
    """

    def __init__(self, entities: list[ContextEntity]) -> None:
        # Build alias → canonical_id index (bounded to supplied context).
        self._index: dict[str, str] = {}
        for entity in entities:
            for alias in entity.all_aliases:
                # First registration wins for collisions (canonical ID takes priority).
                if alias not in self._index:
                    self._index[alias] = entity.canonical_id

    @classmethod
    def from_context_ids(
        cls,
        context_entities: list[str],
        display_names: dict[str, list[str]] | None = None,
    ) -> "EntityResolver":
        """
        Build a resolver from a flat list of canonical entity IDs.

        context_entities: list of canonical IDs (e.g. FIXTURE_CONTEXT_ENTITIES)
        display_names: optional dict mapping canonical_id → [display name, ...]
                       Only use names derivable from the OperationalContextSnapshot
                       or canonical entity metadata — never invent names.
        """
        display_names = display_names or {}
        entities = [
            ContextEntity(
                canonical_id=cid,
                display_names=display_names.get(cid, []),
            )
            for cid in context_entities
        ]
        return cls(entities)

    def resolve(self, text_reference: str) -> str | None:
        """
        Resolve a text reference to a canonical entity ID.

        Returns the canonical ID if found, None if not resolvable.
        Case-insensitive.  Only approved aliases are checked.

        >>> resolver = EntityResolver.from_context_ids(["wave-17"])
        >>> resolver.resolve("wave 17")
        'wave-17'
        >>> resolver.resolve("Wave 17")
        'wave-17'
        >>> resolver.resolve("WAVE-17")
        'wave-17'
        >>> resolver.resolve("Wave 18") is None
        True
        """
        normalized = text_reference.lower().strip()
        return self._index.get(normalized)

    def is_known(self, text_reference: str) -> bool:
        """Return True if text_reference resolves to any known context entity."""
        return self.resolve(text_reference) is not None

    def known_aliases(self) -> frozenset[str]:
        """Return all known surface forms (the full alias index keys)."""
        return frozenset(self._index.keys())


# ── Public API ────────────────────────────────────────────────────────────────


def resolve_entity_reference(
    text_reference: str,
    context_entities: list[str],
) -> str | None:
    """
    Resolve a text reference to a canonical entity ID (§11).

    Deterministic, bounded to supplied context_entities, no external lookup,
    no LLM, no fuzzy global entity search.

    Args:
        text_reference:   Surface-form text from model response.
        context_entities: List of canonical entity IDs in scope.

    Returns:
        Canonical entity ID if resolvable, None otherwise.

    >>> resolve_entity_reference("wave 17", ["wave-17", "conveyor-main"])
    'wave-17'
    >>> resolve_entity_reference("Wave 18", ["wave-17", "conveyor-main"]) is None
    True
    >>> resolve_entity_reference("conveyor main", ["wave-17", "conveyor-main"])
    'conveyor-main'
    """
    resolver = EntityResolver.from_context_ids(context_entities)
    return resolver.resolve(text_reference)


def build_allowed_surface_forms(context_entities: list[str]) -> frozenset[str]:
    """
    Build the complete set of allowed surface forms from context entity IDs.

    Used by graders to expand their allowlist beyond exact canonical IDs.

    Example:
        context_entities = ["wave-17", "conveyor-main"]
        → {"wave-17", "wave 17", "wave_17", "conveyor-main", "conveyor main", "conveyor_main", ...}
    """
    allowed: set[str] = set()
    for canonical_id in context_entities:
        allowed.update(_canonical_aliases(canonical_id))
    return frozenset(allowed)
